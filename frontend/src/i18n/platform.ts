export type PlatformKey = keyof typeof ar

/** Platform strings: Arabic for `ar`, English for every other locale (until translated). */
export function usePt() {
  const i18n = useI18nStore()
  return (key: PlatformKey): string => (i18n.locale === 'ar' ? ar : en)[key]
}

/** Maps a server error code to a localized message. */
export function platformErrorKey(code: string): PlatformKey {
  switch (code) {
    case 'invalid_credentials': return 'invalidCredentials'
    case 'email_taken': return 'emailTaken'
    case 'invalid_email': return 'invalidEmail'
    case 'invalid_password': return 'invalidPassword'
    case 'rate_limited': return 'rateLimited'
    case 'network': return 'networkError'
    case 'already_requested': return 'teachingPending'
    case 'invalid_url': return 'invalidUrl'
    case 'invalid_time': return 'invalidTime'
    case 'not_assigned': return 'notAssigned'
    case 'file_type_not_allowed': return 'fileTypeNotAllowed'
    case 'file_content_mismatch': return 'fileContentMismatch'
    case 'invalid_file_size': return 'invalidFileSize'
    case 'invalid_title': return 'invalidTitle'
    case 'invalid_body': return 'invalidBody'
    case 'not_enrolled': return 'notEnrolled'
    case 'invalid_rating': return 'invalidRating'
    case 'not_open_yet': return 'notOpenYet'
    case 'closed': return 'assessmentClosed'
    case 'no_attempts_left': return 'noAttemptsLeft'
    case 'time_expired': return 'timeExpired'
    case 'already_submitted': return 'alreadySubmitted'
    case 'has_attempts': return 'hasAttempts'
    case 'invalid_points': return 'invalidPoints'
    case 'forbidden': return 'forbidden'
    case 'not_found': return 'notFound'
    case 'cannot_modify_self': return 'cannotModifySelf'
    case 'invalid_name': return 'invalidName'
    case 'invalid_kind':
    case 'invalid_kind_for_school':
    case 'invalid_kind_under_parent': return 'invalidKind'
    default: return 'genericError'
  }
}

export function platformErrorMessage(pt: (k: PlatformKey) => string, e: unknown): string {
  return pt(platformErrorKey(e instanceof PlatformError ? e.code : ''))
}

/** Renders a stored notification (`kind` + `data`) in the current language. */
export function formatNotification(pt: (k: PlatformKey) => string, kind: string, data: Record<string, string | number | null>): string {
  const key = `n_${kind}` as PlatformKey
  let text = pt(key)
  if (!text) return kind
  for (const [k, v] of Object.entries(data)) text = text.replace(`{${k}}`, String(v ?? ''))
  return text
}
