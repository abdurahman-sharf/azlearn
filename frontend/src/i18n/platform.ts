export function platformErrorMessage(pt: (k: PlatformKey) => string, e: unknown): string {
  return pt(platformErrorKey(e instanceof PlatformError ? e.code : ''))
}

/**
 * Like [`platformErrorMessage`] on the grading screens, where a few codes mean something more specific than elsewhere
 * (`invalid_selection` is the bank import's message by default; `not_found` is "the answer or exam is gone").
 */
export function gradingErrorMessage(pt: (k: PlatformKey) => string, e: unknown): string {
  if (e instanceof PlatformError) {
    switch (e.code) {
      case 'invalid_selection': return pt('gdErrSelection')
      case 'invalid_points': return pt('gdBadPoints')
      case 'not_found': return pt('gdErrNotFound')
      case 'forbidden': return pt('gdErrForbidden')
    }
  }
  return platformErrorMessage(pt, e)
}

/**
 * Like [`platformErrorMessage`] for an admin acting on somebody else's exam: `not_assigned` there means the exam's
 * teacher lost the subject (an admin has no assignment of their own), not that the admin is not approved to teach.
 */
export function platformAdminErrorMessage(pt: (k: PlatformKey) => string, e: unknown): string {
  return e instanceof PlatformError && e.code === 'not_assigned' ? pt('errExOwnerNotAssigned') : platformErrorMessage(pt, e)
}

/** Renders a stored notification (`kind` + `data`) in the current language. */
export function formatNotification(
  pt: (k: PlatformKey) => string,
  kind: string,
  data: Record<string, string | number | null>,
  /** Formats timestamp fields (`*_at`, epoch ms) in the viewer's language. */
  fmtTime?: (ms: number) => string,
): string {
  return renderNotification((k) => pt(k as PlatformKey), kind, data, fmtTime)
}

export function auditLabel(pt: (k: PlatformKey) => string, action: string): string {
  return pt(`a_${action}` as PlatformKey) || action
}
